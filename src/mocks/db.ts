/** Everything the demo user can change. Persisted to localStorage. */
export interface PersistedState {
  version: 1
  decisions: Decision[]
  finding_status: Record<string, FindingStatus>
  /** Findings assigned to someone else in this browser: finding id to user id. */
  finding_assignee: Record<string, string>
  rule_enabled: Record<string, boolean>
  read_notifications: string[]
  branches: Branch[]
  audit_appended: AuditEvent[]
  synthetic_jobs: StoredSyntheticJob[]
}

export const STORAGE_KEY = 'dealtrace.demo.v1'

function emptyState(): PersistedState {
  return {
    version: 1,
    decisions: [],
    finding_status: {},
    finding_assignee: {},
    rule_enabled: {},
    read_notifications: [],
    branches: [],
    audit_appended: [],
    synthetic_jobs: [],
  }
}

/** localStorage when available (browser); null in tests or when storage is blocked. */
function storage(): Storage | null {
  try {
    if (typeof window === 'undefined' || !window.localStorage) return null
    return window.localStorage
  } catch {
    return null
  }
}

function isPersistedState(value: unknown): value is PersistedState {
  if (typeof value !== 'object' || value === null) return false
  const v = value as Partial<PersistedState>
  return (
    v.version === 1 &&
    Array.isArray(v.decisions) &&
    typeof v.finding_status === 'object' &&
    typeof v.rule_enabled === 'object' &&
    Array.isArray(v.read_notifications) &&
    Array.isArray(v.branches) &&
    Array.isArray(v.audit_appended) &&
    Array.isArray(v.synthetic_jobs)
  )
}

function load(): PersistedState {
  const s = storage()
  if (!s) return emptyState()
  try {
    const raw = s.getItem(STORAGE_KEY)
    if (!raw) return emptyState()
    const parsed: unknown = JSON.parse(raw)
    // Merge over the empty state so fields added in later versions exist for older saved data.
    return isPersistedState(parsed) ? { ...emptyState(), ...parsed } : emptyState()
  } catch {
    return emptyState()
  }
}

function persist(state: PersistedState): void {
  const s = storage()
  if (!s) return
  try {
    s.setItem(STORAGE_KEY, JSON.stringify(state))
  } catch {
    // Storage full or blocked: keep working in memory.
  }
}

type Listener = () => void

let state: PersistedState = load()
const listeners = new Set<Listener>()

function notify(): void {
  for (const l of listeners) l()
}

/**
 * In-memory store: seed data plus the demo user's changes.
 * Only src/lib/api.ts should use this module.
 */
export const db = {
  seed,

  /** Current mutable state (read-only view; change it through update()). */
  get state(): Readonly<PersistedState> {
    return state
  },

  findings(): Finding[] {
    return seed.findings.map((f) => {
      const status = state.finding_status[f.id]
      const assignee_id = state.finding_assignee[f.id]
      return status || assignee_id ? { ...f, ...(status ? { status } : {}), ...(assignee_id ? { assignee_id } : {}) } : f
    })
  },

  rules(): Rule[] {
    return seed.rules.map((r) => {
      const enabled = state.rule_enabled[r.id]
      return enabled === undefined ? r : { ...r, enabled }
    })
  },

  notifications(): AppNotification[] {
    const read = new Set(state.read_notifications)
    return seed.notifications.map((n) => (read.has(n.id) ? { ...n, read: true } : n))
  },

  /** Seed audit log followed by events appended in this browser, oldest first. */
  audit(): AuditEvent[] {
    return [...seed.audit, ...state.audit_appended]
  },

  update(mutate: (draft: PersistedState) => void): void {
    const draft: PersistedState = structuredClone(state)
    mutate(draft)
    state = draft
    persist(state)
    notify()
  },

  reset(): void {
    state = emptyState()
    const s = storage()
    try {
      s?.removeItem(STORAGE_KEY)
    } catch {
      // ignore
    }
    notify()
  },

  subscribe(listener: Listener): () => void {
    listeners.add(listener)
    return () => listeners.delete(listener)
  },
}
